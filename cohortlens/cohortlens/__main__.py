"""CohortLens command line.

  python -m cohortlens generate                 write the synthetic dataset to data/
  python -m cohortlens run [--mode ...]         run the pipeline and print routing
  python -m cohortlens eval [--reps N]          run the evaluation harness, write runs/evaluations/
  python -m cohortlens export-frontend --out ../impact-lab/cohort-lens/js
  python -m cohortlens export-schemas           JSON Schemas + OpenAPI for the UI
  python -m cohortlens export-data              uploadable CSVs -> ../synthetic data/
  python -m cohortlens serve [--port 8000]      HTTP API for the UI
  python -m cohortlens verify-audit             check the audit hash chain
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .config import DEFAULT_SEED, PROJECT_ROOT, backend_name


def _store():
    from .service import Store
    return Store()


def cmd_generate(a):
    from .synthetic import generate, save
    records, manifest = generate(a.seed)
    path = save(records, manifest)
    print(f"{manifest.n_records} records for {manifest.n_participants} participants -> {path}")
    print(json.dumps(manifest.records_by_stream))
    print(f"dataset hash {manifest.content_hash}")


def cmd_run(a):
    from .schemas import RunConfig
    s = _store()
    cfg = RunConfig(mode=a.mode, backend=a.backend, participants=a.participants or None, label=a.label)
    run_id = s.start_run(cfg, a.perturb, wait=True)
    r = s.runs[run_id]
    if r.status != "completed":
        sys.exit(f"run failed: {r.error}")
    print(f"{run_id}: {len(r.participants)} participants in {r.duration_s}s, {r.llm_calls} agent calls")
    for p in r.participants:
        flag = " *" if p.human_review else ""
        oracle = p.oracle_routing.value if p.oracle_routing else "-"
        print(f"  {p.participant_id}  agent {p.agent_initial_routing.value if p.agent_initial_routing else '-':2} -> final {p.final_routing.value:2}  oracle {oracle:2}{flag}")
    for c in r.cohorts:
        print(f"  cohort {c.cohort} ({c.dose_mg} mg): {c.final_decision.value} (oracle {c.oracle_decision.value})")
    print(f"human review items: {len(r.review_queue)}   result: runs/runs/{run_id}/result.json")


def cmd_eval(a):
    s = _store()
    from .evals import run_evaluation
    res = run_evaluation(s.registry, a.backend, a.reps, a.participants or None, audit=s.audit, progress=lambda m: print("  ..", m))
    path = s.save_evaluation(res)
    for mode, m in res.modes.items():
        print(f"\n[{mode}]")
        for k, v in m.items():
            if isinstance(v, dict) and "numerator" in v:
                print(f"  {k:34} {v['numerator']}/{v['denominator']}" + (f"  ({v['rate']:.3f})" if v["rate"] is not None else ""))
            elif k != "routing_distribution":
                print(f"  {k:34} {v}")
    print("\n[gold claims]")
    for ce in res.claim_eval:
        print(f"  {ce.verifier:30} false approvals {ce.false_approvals.numerator}/{ce.false_approvals.denominator}  "
              f"recall {ce.detection_recall.numerator}/{ce.detection_recall.denominator}  "
              f"precision {ce.detection_precision.numerator}/{ce.detection_precision.denominator}  "
              f"abstention {ce.abstention_accuracy.numerator}/{ce.abstention_accuracy.denominator}")
    print("\n[gates]")
    for g in res.gates:
        state = "n/a " if g.passed is None else ("PASS" if g.passed else "FAIL")
        print(f"  {g.gate_id:5} {state} {g.metric:30} value={g.value} {g.op} {g.threshold}  {g.note}")
    print(f"\n{res.evaluation_id} -> {path}")


def cmd_export_frontend(a):
    from . import frontend
    from .schemas import RunConfig
    s = _store()
    demo = [] if a.clean else ["P-002", "P-003", "P-018", "P-022", "P-026", "P-007"]
    run_id = s.start_run(RunConfig(mode="adversarial", backend=a.backend, label="frontend export"), a.perturb or demo, wait=True)
    run = s.runs[run_id]
    evaluation = None
    if a.with_eval:
        from .evals import run_evaluation
        res = run_evaluation(s.registry, a.backend, a.reps, audit=s.audit)
        s.save_evaluation(res)
        evaluation = json.loads(res.model_dump_json(exclude={"perturbation_outcomes": True, "manifest": True}))
        evaluation["perturbation_outcomes"] = {m: [o.model_dump() for o in outs] for m, outs in res.perturbation_outcomes.items()}
    data = frontend.build(run, s.registry, a.research_associate, evaluation)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    body = json.dumps(data, indent=1, ensure_ascii=False)
    (out / "data.json").write_text(body, encoding="utf-8")
    (out / "data.js").write_text(
        "/*\n * Cohort Lens - generated by `python -m cohortlens export-frontend` from pipeline run "
        f"{run_id}.\n * SYNTHETIC data only. Do not edit by hand: re-run the export instead.\n */\n"
        f"window.COHORT_LENS_DATA = {body};\n", encoding="utf-8")
    print(f"{run_id}: {len(data['patients'])} participants, {sum(p['humanReview'] for p in data['patients'])} for human review -> {out}")


def cmd_export_data(a):
    import shutil
    from .config import CONFIG_DIR
    from .dataset_io import export_csv, write_answer_key
    from .registry import default_registry
    reg = default_registry()
    out = Path(a.out)
    counts = export_csv(reg, out)
    shutil.copy(CONFIG_DIR / "protocol.json", out / "protocol_CVX-214-101.json")
    (out / "dataset_manifest.json").write_text(reg.manifest.model_dump_json(indent=1, exclude={"planted_scenarios"}), encoding="utf-8")
    write_answer_key(reg, out / "answer_key_DO_NOT_UPLOAD")
    for name, n in counts.items():
        print(f"  {name:45} {n} rows")
    print(f"dataset hash {reg.hash} -> {out}")


def cmd_export_schemas(a):
    from pydantic import TypeAdapter
    from . import schemas
    from .api import app
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    names = ["SourceRecord", "DatasetManifest", "Claim", "ClaimVerdict", "VerificationReport", "Critique", "CaseRecord",
             "OracleResult", "Perturbation", "PerturbationManifest", "PerturbationOutcome", "RunConfig", "RunResult",
             "RunSummary", "PipelineEvent", "Persona", "HumanReviewItem", "EvaluationResult", "GateResult", "AuditEntry"]
    for n in names:
        (out / f"{n}.schema.json").write_text(json.dumps(TypeAdapter(getattr(schemas, n)).json_schema(), indent=1), encoding="utf-8")
    (out / "openapi.json").write_text(json.dumps(app.openapi(), indent=1), encoding="utf-8")
    print(f"{len(names)} schemas + openapi.json -> {out}")


def cmd_serve(a):
    import uvicorn
    uvicorn.run("cohortlens.api:app", host=a.host, port=a.port, reload=False)


def cmd_verify_audit(a):
    from .audit import AuditLog
    log = AuditLog(PROJECT_ROOT / "runs" / "audit.jsonl")
    ok, bad = log.verify()
    print(f"{len(log.entries())} entries, chain {'valid' if ok else f'BROKEN at seq {bad}'}")
    sys.exit(0 if ok else 1)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="cohortlens")
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--seed", type=int, default=DEFAULT_SEED)
    g.set_defaults(fn=cmd_generate)
    for name, fn in (("run", cmd_run), ("eval", cmd_eval), ("export-frontend", cmd_export_frontend)):
        p = sub.add_parser(name)
        p.add_argument("--backend", default=backend_name(), choices=["offline", "openrouter", "claude"])
        p.add_argument("--participants", nargs="*")
        p.add_argument("--perturb", nargs="*", help="perturbation IDs from the manifest (e.g. P-003)")
        p.set_defaults(fn=fn)
        if name == "run":
            p.add_argument("--mode", default="adversarial", choices=["adversarial", "single_agent"])
            p.add_argument("--label", default="cli")
        if name in ("eval", "export-frontend"):
            p.add_argument("--reps", type=int, default=10)
        if name == "export-frontend":
            p.add_argument("--out", default=str(PROJECT_ROOT / "frontend_export"))
            p.add_argument("--research-associate", default="Research associate")
            p.add_argument("--clean", action="store_true", help="no demo perturbations")
            p.add_argument("--with-eval", action="store_true", help="embed an evaluation result for the assurance view")
    d = sub.add_parser("export-data", help="write the synthetic dataset as uploadable CSV files")
    d.add_argument("--out", default=str(PROJECT_ROOT.parent / "synthetic data"))
    d.set_defaults(fn=cmd_export_data)
    s = sub.add_parser("export-schemas")
    s.add_argument("--out", default=str(PROJECT_ROOT / "schemas"))
    s.set_defaults(fn=cmd_export_schemas)
    v = sub.add_parser("serve")
    v.add_argument("--host", default="127.0.0.1")
    v.add_argument("--port", type=int, default=8000)
    v.set_defaults(fn=cmd_serve)
    sub.add_parser("verify-audit").set_defaults(fn=cmd_verify_audit)
    a = ap.parse_args(argv)
    a.fn(a)


if __name__ == "__main__":
    main()
